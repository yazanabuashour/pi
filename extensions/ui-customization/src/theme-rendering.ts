type Rgb = [number, number, number];

export const RESET = "\x1b[0m";

export const BOLD = "\x1b[1m";

const PALETTE: Rgb[] = [
  [22, 83, 189],
  [48, 129, 247],
  [93, 171, 255],
  [151, 205, 255],
  [93, 171, 255],
  [48, 129, 247],
];

